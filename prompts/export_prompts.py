GENERATED = "Generated by prompts/export_prompts.py from the code; do not edit by hand."


def block(title: str, text: str) -> str:
    return f"==== {title} ====\n{text.rstrip()}\n==== END ====\n"


def doc(title: str, intro: str, blocks: list) -> str:
    return f"[{title}]\n{GENERATED}\n{intro.strip()}\n\n" + "\n".join(blocks)


class _Captured(Exception):
    pass


def capture_urlopen(module, fn, *args, **kwargs) -> dict:
    """Run `fn` with urllib's urlopen replaced by a recorder; return the
    first request payload it would have sent."""
    seen = []

    def fake_urlopen(req, timeout=None):
        seen.append(json.loads(req.data.decode("utf-8")))
        raise _Captured()

    with mock.patch.object(module.urllib.request, "urlopen", fake_urlopen), \
            mock.patch.object(module.time, "sleep", lambda s: None), \
            mock.patch.object(module.logging, "warning", lambda *a, **k: None):
        fn(*args, **kwargs)
    return seen[0]


def messages(payload: dict) -> tuple:
    msgs = {m["role"]: m["content"] for m in payload["messages"]}
    return msgs.get("system", ""), msgs["user"]



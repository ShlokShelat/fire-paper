"""
Write every prompt FiRE, the baselines and the ablation send to a model into
prompts/*.txt, verbatim, from the code that sends them.

Each message is produced by the real code path with placeholder inputs
(<like this>); where a message is assembled inside a function that makes the
API call, the call is intercepted before anything is sent and the payload is
recorded. No network request is made and no API key is needed.

  python3 prompts/export_prompts.py           # (re)write the files
  python3 prompts/export_prompts.py --check   # exit 1 if a file is out of date

prompts/indian_cultural_glossary.txt is not generated: it is an input (the
structure-guided and knowledge-matched prompts read its table).
"""


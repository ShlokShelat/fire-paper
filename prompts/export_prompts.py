def extraction() -> str:
    unit = S23.ProcessingUnit(
        unit_id="<unit id>", line_number=1, subsection="<section heading>",
        age_context="<age context, or none>", source_type="NARRATIVE",
        stage1_confidence="HIGH",
        sentences=["<section heading>: <the section's note lines, joined into one paragraph>"],
        sentence_objects=[{"source_type": "NARRATIVE"}],
        context_before=["<a nearby line, for reference>"],
        context_after=["<a nearby line, for reference>"])
    return doc(
        "Stages 2-3: extraction prompt (GPT-5.1)",
        "Sent once per note section by src/extraction/fire_stage2_3_single_model.py\n"
        "(reasoning effort \"none\", output limit 2000 tokens, JSON response format).\n"
        "In the paper's runs the system prompt named the partner clinic where it now\n"
        "reads [partner clinic]; nothing else differs.",
        [block("SYSTEM PROMPT (SYSTEM_PROMPT)", S23.SYSTEM_PROMPT),
         block("APPENDED TO THE SYSTEM PROMPT ON THE ONE RETRY OF A HIGH-confidence "
               "SECTION THAT RETURNED NO EVENT (RETRY_NUDGE)", S23.RETRY_NUDGE),
         block("USER MESSAGE (build_prompt_user, placeholder section)",
               S23.build_prompt_user(unit))])


def worker2() -> str:
    calls = []

    async def fake_call_llm(session, api_key, system_prompt, user_prompt, counter,
                            max_retries=3, max_output_tokens=4000):
        calls.append((system_prompt, user_prompt, max_output_tokens))
        return None

    ev = {"unit_id": "<unit id>", "life_stage": "<life stage>", "status": "CONFIRMED",
          "event": "<the event as extracted by Stages 2-3>",
          "source_sentence": "<the event's source text from the notes>",
          "subsection": "<section heading>"}
    with mock.patch.object(W2, "call_llm", fake_call_llm), \
            mock.patch.object(W2, "build_enriched_context",
                              lambda e, s, c: "<the section's other lines, for context>"), \
            mock.patch.object(W2.logging, "error", lambda *a, **k: None):
        asyncio.run(W2.process_event(None, "", None, ev, 1, 1, {}, {}, None, False))
    oracle_sys, oracle_user, oracle_max = calls[0]
    judge = W2.MATCH_JUDGE_PROMPT.format(
        proposed_name="<proposed state name>", proposed_type="<experience type>",
        proposed_desc="<proposed state description>",
        candidates_json="<JSON list of up to 8 candidate states (code, score, name, "
                        "description, cluster_name, experience_type, state_status)>")
    return doc(
        "Worker 2: splitting (Oracle) and matching (Judge) prompts (GPT-5.1)",
        "Sent by src/state_space/fire_worker2.py, reasoning effort \"none\", JSON response\n"
        f"format. Output limits in the code: splitting call {oracle_max} tokens, matching\n"
        "call 300 tokens.",
        [block("SPLITTING CALL — SYSTEM PROMPT (ORACLE_PROMPT)", oracle_sys),
         block("SPLITTING CALL — USER MESSAGE (process_event)", oracle_user),
         block("MATCHING CALL — USER MESSAGE, NO SYSTEM MESSAGE (MATCH_JUDGE_PROMPT)", judge)])


def rescue() -> str:
    payload = capture_urlopen(S5, S5.rescue_call, "<the discarded event>",
                              "<all note lines under the event's section heading>", "<key>")
    system, user = messages(payload)
    return doc(
        "Stage 5: rescue prompt (GPT-5.1)",
        "Sent by src/verification/fire_stage5.py once per discarded event; reasoning\n"
        f"effort \"none\", output limit {payload.get('max_completion_tokens')} tokens. "
        "A Y restores the event; if the call fails, the event is kept but labeled unverified.",
        [block("SYSTEM PROMPT (RESCUE_SYSTEM)", system), block("USER MESSAGE (rescue_call)", user)])


def ace_verification() -> str:
    rec = {"source_sentence": "<source sentence(s)>", "event": "<extracted event>",
           "ace_item": 1, "cluster_name": "<cluster name>", "onset_age": "<onset>",
           "end_age": "<end>"}
    v_sys, v_user = messages(capture_urlopen(W3A, W3A._llm_verify_record, rec, "<key>"))
    a_sys, a_user = messages(capture_urlopen(
        W3A, W3A._llm_adjudicate_drop, rec, 1, "<the first verifier's reason>", "<key>"))
    items = "\n".join(f"  ACE-{n}: {q}" for n, q in W3A.ACE_QUESTIONS.items())
    subq = []
    for n, qs in W3A.ACE_SUBQUESTIONS.items():
        for k, q in enumerate(qs, start=1):
            subq.append(f"  ACE{n}_q{k} [{'DEFINING' if q['defining'] else 'secondary'}]: {q['q']}")
    return doc(
        "Worker 3 (ACE): item check and removal confirmation (GPT-5.1)",
        "Sent by src/instruments/fire_worker3_ace.py with --verify --verify-llm; reasoning\n"
        "effort \"none\". Item check: output limit 2000 tokens, one call per projected\n"
        "item. Removal confirmation: output limit 400 tokens, one call per proposed removal.\n"
        "The user message below is shown for an ACE-1 item (age shown as <onset>-<end>);\n"
        "for another item, that item's text and sub-questions are used.",
        [block("ITEM TEXTS USED IN THESE PROMPTS (ACE_QUESTIONS)", items),
         block("SUB-QUESTIONS PER ITEM (ACE_SUBQUESTIONS)", "\n".join(subq)),
         block("ITEM CHECK — SYSTEM PROMPT (ACE_VERIFY_SYSTEM)", v_sys),
         block("ITEM CHECK — USER MESSAGE (_llm_verify_record, ACE-1)", v_user),
         block("REMOVAL CONFIRMATION — SYSTEM PROMPT (ADJUDICATOR_SYSTEM)", a_sys),
         block("REMOVAL CONFIRMATION — USER MESSAGE (_llm_adjudicate_drop, ACE-1)", a_user)])


def baselines() -> str:
    notes = "<the individual's consultation notes, verbatim>"
    form = OrderedDict((n, "<0 or 1>") for n in range(1, 15))
    assert B0.SYSTEM_PROMPT == B1.SYSTEM_PROMPT and B0.build_user_prompt(notes) == \
        B1.build_user_prompt(notes), "the two plain scripts' notes-only prompts differ"
    out = [block("PLAIN, NOTES ONLY — SYSTEM PROMPT", B1.SYSTEM_PROMPT),
           block("PLAIN, NOTES ONLY — USER MESSAGE", B1.build_user_prompt(notes)),
           block("PLAIN, NOTES + FORM — SYSTEM PROMPT", B1.RECONCILE_SYSTEM_PROMPT),
           block("PLAIN, NOTES + FORM — USER MESSAGE", B1.build_reconcile_prompt(notes, form)),
           block("STRUCTURE-GUIDED, NOTES ONLY — SYSTEM PROMPT", SG.SYSTEM_PROMPT),
           block("STRUCTURE-GUIDED, NOTES ONLY — USER MESSAGE", SG.build_user_prompt(notes)),
           block("STRUCTURE-GUIDED, NOTES + FORM — SYSTEM PROMPT", SG.RECONCILE_SYSTEM_PROMPT),
           block("STRUCTURE-GUIDED, NOTES + FORM — USER MESSAGE",
                 SG.build_reconcile_prompt(notes, form))]
    saved = (SG.PROCEDURE, SG._glossary_block)
    try:
        KM.install("<the state-space file passed with --state-space, trimmed by "
                   "src/baselines/trim_state_space.py and printed as JSON with indent 1>")
        out += [block("KNOWLEDGE-MATCHED, NOTES ONLY — SYSTEM PROMPT", SG.SYSTEM_PROMPT),
                block("KNOWLEDGE-MATCHED, NOTES ONLY — USER MESSAGE", SG.build_user_prompt(notes)),
                block("KNOWLEDGE-MATCHED, NOTES + FORM — SYSTEM PROMPT", SG.RECONCILE_SYSTEM_PROMPT),
                block("KNOWLEDGE-MATCHED, NOTES + FORM — USER MESSAGE",
                      SG.build_reconcile_prompt(notes, form))]
    finally:
        SG.PROCEDURE, SG._glossary_block = saved
    return doc(
        "Baseline prompts (GPT-5.1, Gemini 3.1 Pro, Grok-4.20)",
        "Sent in one call per individual by src/baselines/. GPT-5.1: no temperature, the\n"
        "API's default reasoning effort; Gemini 3.1 Pro and Grok-4.20: temperature 0.\n"
        f"Output limits in the code: fire_llm_baseline.py {B0.MAX_OUTPUT_TOKENS}, "
        f"fire_llm_baseline_self_form_included.py {B1_LIMIT},\n"
        "structure-guided and knowledge-matched 32000 tokens. The plain prompt gives no\n"
        "age-window instruction. With a form, \"<0 or 1>\" is the individual's own answer.",
        out)


def ablation() -> str:
    judge = AB.DIRECT_ITEM_PROMPT.format(
        proposed_name="<proposed state name>", proposed_type="<experience type>",
        proposed_desc="<proposed state description>",
        candidates_json=json.dumps(AB.direct_options(), indent=2, ensure_ascii=False))
    states = [{"state_code": "<state code>", "event": "<event>", "experience_type": "<type>",
               "source_sentence": "<source sentence>", "onset_age": "<onset>",
               "end_age": "<end>"}]
    return doc(
        "Ablation prompts (GPT-5.1)",
        "Used only by src/ablation/fire_ablation.py. --no-state-space replaces Worker 2's\n"
        "matching prompt (same call, same 300-token limit); --model-scoring adds one call per\n"
        "cluster (Worker 3's payload settings, output limit 2000).",
        [block("--no-state-space — USER MESSAGE, NO SYSTEM MESSAGE (DIRECT_ITEM_PROMPT)", judge),
         block("--model-scoring — SYSTEM PROMPT (MODEL_SCORING_SYSTEM)", AB.MODEL_SCORING_SYSTEM),
         block("--model-scoring — USER MESSAGE (one state shown)",
               AB.model_scoring_prompt("<cluster name>", states))])


FILES = {
    "extraction_system_prompt.txt": extraction,
    "oracle_and_judge_prompts.txt": worker2,
    "rescue_prompt.txt": rescue,
    "ace_verification_prompts.txt": ace_verification,
    "baseline_prompts.txt": baselines,
    "ablation_prompts.txt": ablation,
}


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="Exit 1 if any file is out of date.")
    args = ap.parse_args()
    stale = []
    for name, build in FILES.items():
        with mock.patch("sys.stdout", io.StringIO()):
            text = build()
        path = PROMPTS / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"written: prompts/{name}")
    if args.check:
        print("prompts up to date" if not stale else f"out of date: {', '.join(stale)}")
        sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
